/** Run only after the user's explicit fixture-upload consent. Never called by prepare/evaluate. */
import fs from 'node:fs';
import assert from 'node:assert/strict';
import {parseEnv} from 'node:util';
import {artifact,read,write,hash,tokens,fixtures} from './experiment.mjs';
const manifest=read(artifact('upload-manifest.json'));
const consent=read(artifact('consent.json')); // A human authorization record, not generated by this script.
assert.equal(consent.approved,true,'Explicit consent required');
assert.equal(consent.manifestHash,hash(fs.readFileSync(artifact('upload-manifest.json'))),'Consent must match the upload manifest');
assert.equal(manifest.corpusHash,hash(JSON.stringify(read(artifact('corpus.json')))));
for(const [,file,digest] of fixtures)assert.equal(hash(fs.readFileSync(file)),digest);
assert(!fs.existsSync(artifact('embeddings.json')),'Embeddings already cached; do not pay again');
assert(!fs.existsSync(artifact('provider-ledger.json')),'Previous attempt exists; inspect its receipt before authorizing any retry');
const inputs=manifest.upload;
assert.equal(inputs.reduce((n,x)=>n+tokens(x.text),0),manifest.plannedTokens);
assert(manifest.plannedTokens<=50000&&inputs.every(x=>x.tokens>0&&x.tokens<8192));
const env={...(fs.existsSync('.env.local')?parseEnv(fs.readFileSync('.env.local','utf8')):{}),...process.env};
const apiKey=env.OPENAI_API_KEY;assert(apiKey,'OPENAI_API_KEY unavailable (do not print it)');
const ledger={model:manifest.profile.model,dimensions:1536,endpoint:'https://api.openai.com/v1/embeddings',manifestHash:consent.manifestHash,cap:50000,reservedTokens:0,receipts:[]};
const vectors={};
// One request is enough for this corpus. Reserving before transmission prevents ambiguous failures from silently spending twice.
ledger.reservedTokens=manifest.plannedTokens;ledger.status='in-flight';write(artifact('provider-ledger.json'),ledger);
const start=performance.now();
try {
 const response=await fetch(ledger.endpoint,{method:'POST',headers:{Authorization:`Bearer ${apiKey}`,'Content-Type':'application/json'},body:JSON.stringify({model:ledger.model,input:inputs.map(x=>x.text),dimensions:1536,encoding_format:'float'}),signal:AbortSignal.timeout(120000)});
 const body=await response.json();const receipt={httpStatus:response.status,requestId:response.headers.get('x-request-id'),durationMs:performance.now()-start,usage:body.usage??null,model:body.model??null};
 ledger.receipts.push(receipt);write(artifact('provider-ledger.json'),ledger);
 assert(response.ok,`Embedding HTTP ${response.status}; no automatic retry`);
 assert.equal(body.data.length,inputs.length);const seen=new Set();
 for(const row of body.data){assert(Number.isInteger(row.index)&&row.index>=0&&row.index<inputs.length&&!seen.has(row.index));seen.add(row.index);assert.equal(row.embedding.length,1536);assert(row.embedding.every(Number.isFinite));vectors[inputs[row.index].inputHash]=row.embedding;}
 assert(Number.isInteger(body.usage?.total_tokens));assert(body.usage.total_tokens<=50000);
 ledger.actualTokens=body.usage.total_tokens;ledger.estimatedActualUsd=ledger.actualTokens*manifest.priceUsdPerMillion/1e6;ledger.status='complete';
 write(artifact('embeddings.json'),{model:body.model,dimensions:1536,manifestHash:consent.manifestHash,vectors});write(artifact('provider-ledger.json'),ledger);
 console.log(JSON.stringify(ledger,null,2));
} catch(e){ledger.status='failed-or-unknown';ledger.error=String(e);write(artifact('provider-ledger.json'),ledger);throw e;}
